'use strict';

/* End-to-end editor apply proof, on disposable copies only. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'tp-target-apply-'));
const watched = ['world/scene-objects.json', 'world/narrative-targets.json', 'js/scene-objects.gen.js', 'js/world-connections.gen.js'];
const sourceBefore = watched.map((name) => fs.readFileSync(path.join(root, name)));
try {
  for (const dir of ['js', 'test', 'world', 'narrative']) fs.cpSync(path.join(root, dir), path.join(temp, dir), { recursive: true });
  fs.copyFileSync(path.join(root, 'index.html'), path.join(temp, 'index.html'));
  const snapshot = () => watched.map((name) => fs.readFileSync(path.join(temp, name)));
  const run = (op) => {
    const file = path.join(temp, 'target-edit.json');
    fs.writeFileSync(file, JSON.stringify({ format: 'scene-objects-changeset', version: 1,
      target: 'world/scene-objects.json', operations: [op] }));
    return spawnSync(process.execPath, [path.join(root, 'tools/world-apply.js'), file, '--root=' + temp],
      { encoding: 'utf8', timeout: 60000, maxBuffer: 16 * 1024 * 1024 });
  };
  const initial = snapshot();
  let r = run({ op: 'upsert', scene: 'traincar', interact: '4,6', to: '5,6' });
  assert.equal(r.status, 0, r.stdout + r.stderr);
  const context = {}; context.globalThis = context; vm.createContext(context);
  vm.runInContext(fs.readFileSync(path.join(temp, 'js/scene-objects.gen.js'), 'utf8'), context);
  assert.equal(context.GAME.WorldData.narrativeTargets.traincar.bridge_rail.x, 5,
    'moving the physical interaction moves its explicitly bound narrative target');
  assert.equal(context.GAME.WorldData.sceneObjects.scenes.traincar.interact['4,6'], undefined);
  assert.equal(context.GAME.WorldData.sceneObjects.scenes.traincar.interact['5,6'], 'sign_ponte');
  r = run({ op: 'upsert', scene: 'traincar', interact: '5,6', to: '4,6' });
  assert.equal(r.status, 0, r.stdout + r.stderr);
  assert.deepEqual(snapshot(), initial, 'moving back restores exact data and generated bytes');
  r = run({ op: 'delete', scene: 'traincar', interact: '4,6' });
  assert.equal(r.status, 1, r.stdout + r.stderr);
  assert.match(r.stderr, /binding sign_ponte resolves to 0 entries/);
  assert.deepEqual(snapshot(), initial, 'a referenced-target deletion rolls back every changed file');
  assert.deepEqual(watched.map((name) => fs.readFileSync(path.join(root, name))), sourceBefore,
    'the actual checkout is not modified by the test');
  console.log('narrative-targets-apply: editor move follows binding, reverse restores bytes, referenced deletion rolls back PASS');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
